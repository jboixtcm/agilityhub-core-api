def main():
    out = ['# E11-T12 · literal tails of every evidence log', '',
           'Generated by `python3 roadmap/evidence/E11-T12/tails.py`. Each section: the command, its exit code, the log\'s line',
           'count and its last 40 lines, verbatim. The PIT batch logs (`07-NN-pit-*.log`) carry their command in the',
           '`.command` file and their exit code in the `.exit` file next to them.', '']
    logs = sorted(HERE.glob('*.log'))
    for log in logs:
        lines = log.read_text(errors='replace').splitlines()
        command_file = log.with_suffix('.command')
        if log.name in COMMANDS:
            command, code = COMMANDS[log.name]
        elif command_file.exists():
            command = command_file.read_text().strip()
            code = log.with_suffix('.exit').read_text().strip().removeprefix('exit ')
        else:
            command, code = '(see the task report)', '?'
        out += [f'## {log.name}', '', f'- command: `{command}`', f'- exit code: {code}', f'- lines: {len(lines)}', '',
                '```text', *lines[-40:], '```', '']
    (HERE / '00-tails.md').write_text('\n'.join(out) + '\n')
    print(f'00-tails.md: {len(logs)} logs')


if __name__ == '__main__':
    main()
