package com.agilityhub.core.arch;

import com.tngtech.archunit.core.importer.ClassFileImporter;
import com.tngtech.archunit.core.importer.ImportOption;
import java.lang.reflect.Method;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.stream.Collectors;
import org.junit.jupiter.api.Test;
import org.springframework.core.annotation.AnnotatedElementUtils;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.stereotype.Controller;
import org.springframework.util.AntPathMatcher;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestMethod;
import static org.assertj.core.api.Assertions.assertThat;

/**
 * REL-06 (pre-production audit, 11-11-2026): the role rule of every request mapping, one line per HTTP method and path with the
 * `@PreAuthorize` expression (method's, else its class's; `none` for a listed open route, AUTHZ-03) and the handler, against the
 * committed snapshot `src/test/resources/snapshots/security/handler-roles.txt`. A new route, or a role rule that changes, fails
 * here until the snapshot is regenerated with `-Dsnapshots.update=true`: the diff is the review, against
 * `docs/specs/00-transversal/MATRIU_PERMISOS.md`. {@link ArchitectureRules#HANDLER_ROLES} checks that a rule exists; this
 * test shows which one.
 */
class HandlerRolesSnapshotTest {
    private static final String BASE_PACKAGE = "com.agilityhub.core.";
    private static final Path SNAPSHOT = Path.of("src/test/resources/snapshots/security/handler-roles.txt");
    private static final AntPathMatcher PATHS = new AntPathMatcher();

    static List<String> table() {
        var lines = new ArrayList<String>();
        var classes = new ClassFileImporter().withImportOption(ImportOption.Predefined.DO_NOT_INCLUDE_TESTS).importPackages("com.agilityhub.core");
        for (var javaClass : classes) {
            if (!javaClass.isMetaAnnotatedWith(Controller.class) && !javaClass.isAnnotatedWith(Controller.class)) { continue; }
            Class<?> type = javaClass.reflect();
            var classMapping = AnnotatedElementUtils.findMergedAnnotation(type, RequestMapping.class);
            var classRule = AnnotatedElementUtils.findMergedAnnotation(type, PreAuthorize.class);
            for (Method method : type.getDeclaredMethods()) {
                if (method.isSynthetic() || method.isBridge()) { continue; }
                var mapping = AnnotatedElementUtils.findMergedAnnotation(method, RequestMapping.class);
                if (mapping == null) { continue; }
                var rule = AnnotatedElementUtils.findMergedAnnotation(method, PreAuthorize.class);
                String roles = rule != null ? rule.value() : classRule != null ? classRule.value() : "none";
                String handler = type.getName().substring(BASE_PACKAGE.length()) + "." + method.getName();
                var verbs = mapping.method().length > 0 ? mapping.method() : classMapping != null ? classMapping.method() : new RequestMethod[0];
                String methods = verbs.length == 0 ? "ANY" : Arrays.stream(verbs).map(Enum::name).sorted().collect(Collectors.joining(","));
                for (String prefix : paths(classMapping)) {
                    for (String path : paths(mapping)) {
                        lines.add(methods + " " + PATHS.combine(prefix, path) + " | " + roles + " | " + handler);
                    }
                }
            }
        }
        return lines.stream().sorted().toList();
    }

    private static List<String> paths(RequestMapping mapping) {
        return mapping == null || mapping.path().length == 0 ? List.of("") : List.of(mapping.path());
    }

    @Test void REL_06_everyHandlersRoleRuleMatchesTheCommittedSnapshot() throws Exception {
        var table = table();
        String out = "# REL-06 handler roles · generated by HandlerRolesSnapshotTest (-Dsnapshots.update=true)\n"
                + "# <methods> <path> | <@PreAuthorize of the method, else of its class; none = open route> | <handler>\n"
                + "# Review every changed line against docs/specs/00-transversal/MATRIU_PERMISOS.md.\n"
                + String.join("\n", table) + "\n";
        if (Boolean.getBoolean("snapshots.update")) { Files.createDirectories(SNAPSHOT.getParent()); Files.writeString(SNAPSHOT, out); }
        assertThat(table).as("the scan finds the controllers").hasSizeGreaterThan(400);
        assertThat(table).as("a handler without a rule is a listed open route (AUTHZ-03)")
                .filteredOn(line -> line.contains(" | none | "))
                .allSatisfy(line -> assertThat(ArchitectureRules.OPEN_HANDLERS).contains(line.substring(line.lastIndexOf(" | ") + 3)));
        assertThat(SNAPSHOT).as("run once with -Dsnapshots.update=true and review the diff").exists();
        assertThat(out).as("a route or role rule changed: run with -Dsnapshots.update=true and review the diff against MATRIU_PERMISOS")
                .isEqualTo(Files.readString(SNAPSHOT));
    }
}
